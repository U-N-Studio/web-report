import * as fs from 'fs';
import * as path from 'path';
import { IPC_CHANNELS } from '../shared/ipc';

type ParamEntry = { name: string; type: string };
type ChannelMapping = { params: ParamEntry[]; handler: string };

const channelMap: Record<string, ChannelMapping> = {
  'fetch-homepage': { params: [{ name: 'platform', type: 'string' }], handler: 'reportService.fetchHomepage' },
  'search-videos': { params: [{ name: 'params', type: '{ platform: string; keyword: string; url?: string }' }], handler: 'reportService.searchVideos' },
  'analyze-video': { params: [{ name: 'params', type: '{ platform: string; videoId: string; aiMode: string; modelName?: string; customRules?: string }' }], handler: 'reportService.analyzeAndSaveReport' },
  'get-reports': { params: [], handler: 'reportService.getReports' },
  'get-report-detail': { params: [{ name: 'reportId', type: 'string' }], handler: 'reportService.getReportDetail' },
  'update-comment-status': { params: [{ name: 'commentId', type: 'string' }, { name: 'isViolation', type: 'boolean' }], handler: 'reportService.updateCommentStatus' },
  'get-settings': { params: [], handler: 'reportService.getSettingsData' },
  'save-settings': { params: [{ name: 'settings', type: 'Settings' }], handler: 'reportService.saveSettingsData' },
};

const declared = new Set<string>(IPC_CHANNELS);
const defined = new Set<string>(Object.keys(channelMap));

const missing = [...declared].filter((c) => !defined.has(c));
const extra = [...defined].filter((c) => !declared.has(c));

if (missing.length > 0) {
  console.error(`[gen-ipc] Channels in IPC_CHANNELS but missing handler mapping:`);
  for (const c of missing) console.error(`  - ${c}`);
}
if (extra.length > 0) {
  console.error(`[gen-ipc] Channels in IpcChannels but missing from IPC_CHANNELS:`);
  for (const c of extra) console.error(`  - ${c}`);
}
if (missing.length > 0 || extra.length > 0) process.exit(1);

const lines: string[] = [
  `// @generated by scripts/gen-ipc.ts — DO NOT EDIT`,
  `// To add a channel, edit shared/ipc.ts and re-run npm run gen-ipc`,
  ``,
  `import type { IpcChannelName, IpcParams, IpcReturns, Settings } from '@shared/ipc';`,
  `import * as reportService from '../services/report';`,
  ``,
  `export const ipcHandlers: {`,
  `  [C in IpcChannelName]: (...args: IpcParams<C>) => IpcReturns<C>;`,
  `} = {`,
];

for (const channel of IPC_CHANNELS) {
  const def = channelMap[channel];
  const [serviceRef, method] = def.handler.split('.');
  const paramSig = def.params.map((p) => `${p.name}: ${p.type}`).join(', ');
  const paramCall = def.params.map((p) => p.name).join(', ');
  lines.push(`  '${channel}': (${paramSig}) => ${serviceRef}.${method}(${paramCall}),`);
}

lines.push(`};`);
lines.push(``);

const outPath = path.resolve(__dirname, '../electron/ipc/handlers.ts');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`[gen-ipc] Generated electron/ipc/handlers.ts (${IPC_CHANNELS.length} channels)`);
